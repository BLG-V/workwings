type LegalBackFrom = '/' | '/login' | '/register'

function resolveLegalBack(from: unknown): { to: LegalBackFrom; label: string } {
  if (from === '/') return { to: '/', label: '返回引导页' }
  if (from === '/register') return { to: '/register', label: '返回注册' }
  return { to: '/login', label: '返回登录' }
}

